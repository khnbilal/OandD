export const WORKOUT_ORDER: Record<Level, string[]> = {
  Beginner: [
    'warm-up', 'burst', 'accelerate', 'flow-down', 'agility', 'speed',
    'momentum', 'blast', 'slimmer', 'lean-out', 'dynamic', 'torch',
    'tone', 'tighten', 'strengthen', 'invigorate',
  ],
  Intermediate: [
    'warm-up', 'flow-down', 'speed', 'agility', 'momentum', 'accelerate',
    'burst', 'blast', 'slimmer', 'lean-out', 'dynamic', 'torch',
    'tone', 'tighten', 'strengthen', 'invigorate',
  ],
};

export function getOrderedWorkouts(level: Level, items: Workout[] = workouts): Workout[] {
  const rank = new Map<string, number>(WORKOUT_ORDER[level].map((id, index): [string, number] => [id, index]));
  return items
    .filter((workout) => workout.level === level)
    .sort((a, b) => (rank.get(a.id) ?? Number.MAX_SAFE_INTEGER) - (rank.get(b.id) ?? Number.MAX_SAFE_INTEGER));
}
